const assert=require('assert'),fs=require('fs'),vm=require('vm'),path=require('path');
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../frontend/js/timeline.js'),'utf8'),context);
const {videoTimeline,locateVideo,formatPreviewTime}=context;
const items=[{name:'a',duration_s:901.7},{name:'b',duration_s:900},{name:'c',duration_s:5400.25}];
const timeline=videoTimeline(items);
assert.equal(timeline.at(-1).end_s,7201.95);
assert.equal(locateVideo(timeline,901.699).index,0);
assert.equal(locateVideo(timeline,901.7).index,1);
assert.equal(locateVideo(timeline,901.7).local_time_s,0);
assert.equal(locateVideo(timeline,1801.7).index,2);
assert.equal(locateVideo(timeline,1801.7).local_time_s,0);
assert.equal(locateVideo(timeline,-5).local_time_s,0);
assert.equal(locateVideo(timeline,99999).local_time_s,5400.249);
assert.equal(formatPreviewTime(7201.95),'7201.9초 (2시간 0분 2초)');
assert.equal(formatPreviewTime(3599.95),'3599.9초 (1시간 0분 0초)');
assert.equal(formatPreviewTime(900),'900.0초 (15분 0초)');
assert.equal(videoTimeline([items[1],items[0]])[1].start_s,900);
assert.throws(()=>videoTimeline([{name:'bad',duration_s:NaN}]));
assert.throws(()=>locateVideo([],0));
console.log('PASS: cumulative times, file boundaries, final endpoint, hours and reordered files');
